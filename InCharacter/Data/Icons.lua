local function art(icon, words, category, label)
    local path = I .. icon
    IC.IconChoices[#IC.IconChoices + 1] = { path = path, label = label or words, category = category, search = words }
    for word in words:gmatch("%S+") do IC.EmoteIcons[word] = path end
end
