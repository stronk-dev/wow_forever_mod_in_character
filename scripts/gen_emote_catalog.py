#!/usr/bin/env python3
"""Regenerate InCharacter/Data/EmoteCatalog.lua from Warcraft Wiki's emote table.

Usage:
    curl -sL "https://warcraft.wiki.gg/wiki/List_of_emotes?action=raw" -o list.wiki
    python3 scripts/gen_emote_catalog.py list.wiki

Only facts are kept: command, aliases and the wiki's Anim / Voice flags.
Rows greyed out on the wiki (removed or changed in patch 9.1.5) are skipped.
The addon still checks every emote against the running client's token table.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1]).read_text(encoding="utf-8")
table = source.split("<onlyinclude>")[1].split("</onlyinclude>")[0]
parts = re.split(r"\n\|-([^\n]*)\n", table)
rows = []
for attributes, body in zip(parts[1::2], parts[2::2]):
    body = body.strip()
    if "qc-poor" in attributes or not body.startswith("|") or body.startswith("|}"):
        continue
    cells = [cell.strip() for cell in body[1:].split("||")]
    command_cell = re.sub(r"<[^>]*>", " ", cells[0]).lower() if cells else ""
    commands = re.findall(r"(?<![a-z0-9])/([a-z0-9]+)", command_cell)
    if len(cells) < 3 or not commands:
        continue
    flags = ("A" if "✔" in cells[1] else "") + ("V" if "✔" in cells[2] else "")
    rows.append(" ".join(commands) + ("|" + flags if flags else ""))

lines = [
    "local _, IC = ...",
    "-- GENERATED by scripts/gen_emote_catalog.py; do not edit by hand.",
    "-- Source: https://warcraft.wiki.gg/wiki/List_of_emotes (Anim / Voice columns).",
    "-- Format: \"command alias alias|flags\"; A = plays an animation, V = voice/sound nearby players hear.",
    "-- The wiki documents Retail. In Character marks an emote usable only when this client knows its token.",
    "IC.EmoteCatalog = {",
]
lines += [f'    "{row}",' for row in rows]
lines.append("}")
out = ROOT / "InCharacter" / "Data" / "EmoteCatalog.lua"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{out}: {len(rows)} emotes")
