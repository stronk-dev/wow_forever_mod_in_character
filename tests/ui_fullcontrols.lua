return function(test, eq, page)
    local function allEmotes(IC, env)
        for i, action in ipairs(IC.Emotes.list) do env["EMOTE" .. i .. "_TOKEN"], env["EMOTE" .. i .. "_CMD1"] = action.payload, "/" .. action.command end
        IC.Emotes.Validate()
    end
    local function pool(IC, name, count)
        local p = IC.Dialogue.Create(name); local lines = {}; for i = 1, count do lines[i] = name .. " " .. i end
        IC.Dialogue.Save(p, name, "SAY", "sequential", p.icon, lines); return p
    end
    local function item(IC, id)
        for _, row in ipairs(IC.LayoutUI.frame.rows) do if row:IsShown() and row.action.id == id then return row end end
        error("No layout item " .. id)
    end
    test("radial command and key remain radial for every optional quick style and never hide bars", function(IC, Stub, env)
        for _, style in ipairs({ "bars", "panel", "ring" }) do
            IC.Profile().quick.style = style
            IC.Slash("wheel"); assert(IC.Wheel.open); assert(IC.Bars.frames[1]:IsShown() and IC.Bars.frames[2]:IsShown())
            IC.Wheel.Close(); env.InCharacter_WheelBinding("down"); assert(IC.Wheel.open)
            env.InCharacter_WheelBinding("up"); assert(IC.Wheel.open); IC.Wheel.Close()
            IC.Slash("menu"); assert(IC.Menu.IsOpen()); assert(IC.Bars.frames[2]:IsShown()); IC.Menu.Close()
        end
        eq(#Stub.emotes + #Stub.sends, 0); assert(Stub.KeyDown("W"))
    end)
    test("launcher buttons are independently configured for wheel menu bars editing and settings", function(IC, Stub)
        local p = page(IC, "Layouts")
        p.lClick:Choose("wheel"); p.lRight:Choose("menu"); p.lMiddle:Choose("edit")
        IC.Editor.frame:Hide(); IC.Launcher.button:Click(); assert(IC.Wheel.open)
        IC.Launcher.button:Click("RightButton"); assert(IC.Menu.IsOpen()); assert(not IC.Wheel.open)
        IC.Launcher.button:Click("MiddleButton"); assert(IC.Bars.editing); assert(not IC.Menu.IsOpen())
        IC.Bars.SetEditing(false); Stub.modifiers.shift = true; IC.Launcher.button:Click("RightButton"); Stub.modifiers.shift = nil
        assert(IC.Editor.frame:IsShown()); p.lClick:Choose("bars"); IC.Launcher.button:Click(); assert(IC.Layout().bars[2].hidden)
        eq(IC.Layout().launcher.rightClick, "menu"); eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("Home and Blizzard settings each expose independent wheel menu and unified edit controls", function(IC, Stub)
        local home = page(IC, "Home"); home.openWheel:Click(); assert(IC.Wheel.open)
        page(IC, "Home").openMenu:Click(); assert(IC.Menu.IsOpen()); assert(not IC.Wheel.open)
        page(IC, "Home").editAll:Click(); assert(IC.Bars.editing); assert(not IC.Editor.frame:IsShown())
        IC.Bars.SetEditing(false); IC.SettingsPanel.panel.openWheel:Click(); assert(IC.Wheel.open)
        IC.SettingsPanel.panel.openMenu:Click(); assert(IC.Menu.IsOpen()); IC.SettingsPanel.panel.editLayouts:Click(); assert(IC.Bars.editing)
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("RP bars have normal native two-axis resize in play and preserve their top-left edge", function(IC, Stub)
        for i = 1, 9 do pool(IC, "Tone " .. i, 2) end
        local frame = IC.Bars.frames[2]; assert(frame.resizeHandle:IsShown()); assert(not IC.Bars.editing)
        eq(frame.buttons[1].template, "UIPanelButtonTemplate"); eq(frame.buttons[1]:GetNormalTexture().width, nil)
        frame.buttons[1]:Fire("OnEnter"); frame.buttons[1]:Fire("OnLeave")
        eq(frame.resizeHandle.point, "BOTTOMRIGHT")
        local left, top = frame:GetLeft(), frame:GetTop()
        frame.resizeHandle:Fire("OnMouseDown", "LeftButton"); eq(frame.sizing, "BOTTOMRIGHT")
        frame:SetSize(320, 240); eq(frame.config.width, 320); eq(frame.config.height, 240)
        frame.resizeHandle:Fire("OnMouseUp", "LeftButton")
        eq(frame:GetLeft(), left); eq(frame:GetTop(), top); eq(frame:GetWidth(), 320); eq(frame:GetHeight(), 240)
        assert(frame.next:IsShown()); assert(frame.next.x <= -24); local before = frame.config.page; frame.next:Click(); assert(frame.config.page ~= before)
        eq(#Stub.sends, 0); Stub.Tick(0.2); frame.buttons[1]:Click(); eq(#Stub.sends, 1)
    end)
    test("exact-message bars and icon grids use the same native corner resize", function(IC, Stub)
        local p = pool(IC, "Jokes", 7); IC.Bars.OpenLines(2, p.id)
        local lines = IC.Bars.frames[3]; assert(lines.resizeHandle:IsShown())
        lines.resizeHandle:Fire("OnMouseDown", "LeftButton"); lines:SetSize(300, 220); lines.resizeHandle:Fire("OnDragStop")
        eq(lines.config.width, 300); eq(lines.config.height, 220); eq(lines:GetWidth(), 300)
        local editor = page(IC, "Layouts"); editor.which:Choose(1); editor.bStyle:Choose("icons")
        local grid = IC.Bars.frames[1]; grid.resizeHandle:Fire("OnMouseDown", "LeftButton"); grid:SetSize(280, 140); grid.resizeHandle:Fire("OnDragStop")
        eq(grid.config.width, 280); eq(grid.config.height, 140); eq(#Stub.sends + #Stub.emotes, 0)
        grid.config.source = "pool:" .. p.id; grid.config.strip = true; IC.Refresh()
        grid.buttons[1]:Click("RightButton"); eq(#IC.Layout().bars, 3)
        eq(IC.Layout().bars[3].source, "lines:" .. p.id); assert(IC.Bars.frames[3]:IsShown()); eq(#Stub.sends, 0)
    end)
    test("edit inspector selects every bar and updates actual source style size visibility and RP tabs", function(IC, Stub)
        pool(IC, "Jokes", 2); IC.Slash("edit"); local p = IC.Bars.inspector
        p.which:Choose(2); eq(IC.Editor.barIndex, 2); assert(IC.Bars.frames[2].moveHandle:IsShown())
        assert(p.playback:IsShown()); p.playback:Choose("sequential"); eq(IC.Layout().bars[2].poolMode, "sequential")
        p.width:SetValue(380); p.height:SetValue(180); eq(IC.Bars.frames[2]:GetWidth(), 380); eq(IC.Bars.frames[2]:GetHeight(), 180)
        p.tabs:SetChecked(false); p.tabs:Click(); eq(IC.Bars.GroupRows(IC.Layout().bars[2], 380), 0)
        p.hidden:SetChecked(true); p.hidden:Click(); assert(not IC.Bars.frames[2]:IsShown())
        p.hidden:SetChecked(false); p.hidden:Click(); assert(IC.Bars.frames[2]:IsShown())
        p.which:Choose(1); p.source:Choose("categories"); p.view:Choose("all"); p.style:Choose("icons"); p.size:SetValue(28)
        eq(IC.Layout().bars[1].source, "categories"); eq(IC.Layout().bars[1].emoteView, "all"); eq(IC.Layout().bars[1].size, 28)
        for id, check in pairs(p.categoryChecks) do check:SetChecked(id == "Social"); check:Click() end
        for _, action in ipairs(IC.Presentation.BarActions(IC.Layout().bars[1])) do assert(action.categories.Social) end
        eq(#Stub.sends + #Stub.emotes, 0)
    end)
    test("edit mode cannot dispatch emotes pools or exact lines even through an alternate UI", function(IC, Stub)
        local p = pool(IC, "Do not send", 2); IC.Bars.SetEditing(true)
        for _, id in ipairs({ "emote:wave", "pool:" .. p.id, "play:random:" .. p.id, "line:" .. p.id .. ":" .. p.lineIDs[1] }) do
            local ok, reason = IC.Actions.Dispatch(id); assert(not ok); assert(reason:find("editing", 1, true))
        end
        IC.Bars.frames[1].buttons[1]:Click(); eq(IC.Bars.selectedBar, 1)
        eq(#Stub.sends + #Stub.emotes, 0); eq(next(IC.Dialogue.states), nil)
    end)
    test("filtered emote checkboxes explain absence and explicitly restore that bar alone", function(IC, Stub, env)
        allEmotes(IC, env); IC.Curation.Save("emote:hug", "hide", "unknown", "unknown")
        local bars = IC.Layout().bars; bars[1].source = "Social"
        bars[3] = IC.Defaults.EmoteBar(3, "Social"); IC.Refresh(); IC.LayoutUI.Open("bar", 1)
        local row = item(IC, "emote:hug"); assert(not row.check:GetChecked()); assert(row.check.caption:GetText():find("filtered", 1, true))
        row.check:SetChecked(true); row.check:Click(); assert(item(IC, "emote:hug").check:GetChecked())
        local function has(c) for _, action in ipairs(IC.Presentation.BarActions(c)) do if action.id == "emote:hug" then return true end end end
        assert(has(bars[1])); assert(not has(bars[3])); eq(IC.Curation.Record("emote:hug").choice, "hide")
        row = item(IC, "emote:hug"); row.check:SetChecked(false); row.check:Click(); assert(not has(bars[1]))
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("all recognized emotes are recoverable in the bar item editor without changing global curation", function(IC, Stub, env)
        allEmotes(IC, env); IC.Layout().bars[1].source = "all"; IC.Refresh()
        local before = #IC.Presentation.BarActions(IC.Layout().bars[1]); IC.LayoutUI.Open("bar", 1)
        IC.LayoutUI.frame.emoteChoice:Choose("all"); assert(#IC.Presentation.BarActions(IC.Layout().bars[1]) > before)
        eq(IC.Profile().emoteScope, "essentials")
        for _, action in ipairs(IC.Presentation.BarActions(IC.Layout().bars[1])) do assert(action.verified) end
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("unrecognized definitions remain flagged in the editor and do not masquerade as enabled commands", function(IC, Stub)
        IC.Layout().bars[1].source = "all"; IC.Layout().bars[1].emoteView = "all"; IC.Refresh(); IC.LayoutUI.Open("bar", 1)
        local row = item(IC, "emote:flex"); assert(not row.check:GetChecked()); assert(not row.check:IsEnabled()); assert(row.check.caption:GetText():find("not on this client", 1, true))
        for _, action in ipairs(IC.Presentation.BarActions(IC.Layout().bars[1])) do assert(action.id ~= "emote:flex") end
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("WoW Edit Mode callbacks open and close the exact same inspector and cancel active input", function(IC, Stub, env)
        local p = page(IC, "Layouts"); p.wKey:Click(); assert(p.wKey.capturing)
        env.EventRegistry:TriggerEvent("EditMode.Enter"); assert(IC.Bars.editing); assert(IC.Bars.inspector:IsShown()); assert(not p.wKey.capturing)
        assert(IC.Bars.frames[1].moveHandle:IsShown() and IC.Bars.frames[2].moveHandle:IsShown())
        env.EventRegistry:TriggerEvent("EditMode.Exit"); assert(not IC.Bars.editing); assert(not IC.Bars.inspector:IsShown()); assert(Stub.KeyDown("W"))
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("standalone edit controls work without the optional client Edit Mode callback registry", function(IC, Stub, env)
        env.EventRegistry = nil; IC.Bars.editModeConnected = nil; IC.Bars.ConnectEditMode(); assert(not IC.Bars.editModeConnected)
        IC.Slash("edit"); assert(IC.Bars.editing); IC.Bars.inspector:Hide(); assert(not IC.Bars.editing); assert(Stub.KeyDown("W"))
    end)
    test("Undo restores layout changes and added bars while preserving newly edited dialogue", function(IC, Stub)
        local c = IC.Layout().bars[1]; local width = c.stripWidth; local count = #IC.Layout().bars
        IC.Bars.SetEditing(true); local p = IC.Bars.inspector
        p.width:SetValue(500); Stub.Button(p, "+ RP bar"):Click(); eq(#IC.Layout().bars, count + 1)
        local quotes = pool(IC, "Keep this text", 2); Stub.Button(p, "Undo"):Click()
        eq(#IC.Layout().bars, count); eq(IC.Layout().bars[1].stripWidth, width); eq(#IC.Profile().pools[quotes.id].lines, 2)
        assert(IC.Bars.editing); eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("radial and context item editing stay connected to unified layout editing", function(IC, Stub)
        IC.Bars.SetEditing(true); local p = IC.Bars.inspector
        Stub.Button(p, "Radial items"):Click(); eq(IC.LayoutUI.frame.kind, "wheel"); assert(IC.Bars.editing)
        IC.Editor.frame:Hide(); Stub.Button(p, "Context items"):Click(); eq(IC.LayoutUI.frame.kind, "menu"); assert(IC.Bars.editing)
        eq(#Stub.emotes + #Stub.sends, 0)
    end)
    test("the launcher participates in Edit Mode with live independent mouse choices and movement", function(IC, Stub)
        IC.Bars.SetEditing(true); IC.Launcher.button:Click(); local p = IC.Bars.inspector
        assert(IC.Bars.selectedLauncher and p.launcherForm:IsShown()); assert(not p.form:IsShown())
        p.launcherLeft:Choose("menu"); p.launcherRight:Choose("wheel"); p.launcherMiddle:Choose("bars"); p.launcherSize:SetValue(48)
        eq(IC.Launcher.button:GetWidth(), 48)
        IC.Launcher.button:Fire("OnDragStart"); assert(IC.Launcher.button.moving)
        IC.Launcher.button:SetPoint("CENTER", 180, 100); IC.Launcher.button:Fire("OnDragStop")
        eq(IC.Layout().launcher.x, 180); eq(IC.Layout().launcher.y, 100)
        IC.Bars.SetEditing(false); Stub.Tick(0.2); IC.Launcher.button:Click(); assert(IC.Menu.IsOpen())
        IC.Launcher.button:Click("RightButton"); assert(IC.Wheel.open)
        eq(#Stub.sends + #Stub.emotes, 0)
    end)
    test("Edit Mode supports an empty layout and can add a new bar after selecting the launcher", function(IC, Stub)
        IC.Layout().bars = {}; IC.Refresh(); IC.Bars.SetEditing(true); local p = IC.Bars.inspector
        assert(p.launcherForm:IsShown()); Stub.Button(p, "+ RP bar"):Click()
        eq(#IC.Layout().bars, 1); assert(p.form:IsShown()); assert(not p.launcherForm:IsShown()); eq(IC.Bars.selectedBar, 1)
        assert(IC.Bars.frames[1].resizeHandle:IsShown()); eq(#Stub.sends + #Stub.emotes, 0)
    end)
    test("native labeled buttons use the height-scaled client template when its mixin is available", function(IC, Stub, env)
        env.UIPanelButtonHeightScaledMixin = {}
        pool(IC, "Native-size buttons", 2); local button = IC.Bars.frames[2].buttons[1]
        eq(button.template, "UIPanelButtonHeightScaledTemplate"); eq(button:GetNormalTexture().width, nil)
        button:Fire("OnEnter"); button:Fire("OnLeave"); eq(#Stub.sends, 0)
    end)
end
