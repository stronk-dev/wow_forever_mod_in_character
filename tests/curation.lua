return function(IC, test, eq, open)
    local function contains(list, id) for _, value in ipairs(list) do if value == id then return true end end end
    test("default selection trims flavour and variants without limiting what a player can keep", function()
        open(); local profile = IC.Profile()
        eq(profile.emoteScope, "essentials"); eq(profile.quick.style, "bars")
        assert(IC.Curation.Included(IC.Actions.Resolve("emote:laugh")))
        assert(not IC.Curation.Included(IC.Actions.Resolve("emote:giggle")))
        assert(not IC.Curation.Included(IC.Actions.Resolve("emote:hug")))
        assert(IC.Curation.Save("emote:hug", "keep", "unknown", "unknown"))
        assert(IC.Curation.Included(IC.Actions.Resolve("emote:hug")))
        profile.emoteScope = "all"; assert(IC.Curation.Included(IC.Actions.Resolve("emote:giggle")))
    end)
    test("hiding a pinned emote retains its slot and can be reversed without deleting data", function()
        open(); local count = #IC.Profile().favorites; local first = IC.Profile().favorites[1]
        IC.Curation.Save(first, "hide", "silent", "yes", "", "not useful to me")
        assert(not IC.Curation.Included(IC.Actions.Resolve(first))); eq(#IC.Profile().favorites, count); eq(IC.Profile().favorites[1], first)
        IC.Curation.Save(first, "keep", "silent", "yes"); assert(IC.Curation.Included(IC.Actions.Resolve(first)))
    end)
    test("self-heard audio never becomes an assertion that nearby players hear it", function()
        open(); local action = IC.Actions.Resolve("emote:chicken")
        assert(not IC.Emotes.IsAudible(action)); assert(IC.Emotes.Badge(action):find("Not checked", 1, true))
        IC.Curation.Save(action.id, "keep", "self", "yes")
        assert(not IC.Emotes.IsAudible(action)); assert(IC.Emotes.Badge(action):find("You heard", 1, true))
        IC.Curation.Save(action.id, "keep", "nearby", "yes")
        assert(IC.Emotes.IsAudible(action)); assert(IC.Emotes.Badge(action):find("Others heard", 1, true))
    end)
    test("audio and animation observations stay per character while choices can be shared", function()
        local db = open(); IC.Curation.Save("emote:wave", "keep", "self", "yes")
        open(db, "Realm:Other"); eq(IC.Curation.Observation("emote:wave").sound, nil)
        eq(IC.Curation.Record("emote:wave").choice, "keep")
        IC.Curation.Save("emote:wave", "keep", "silent", "no")
        open(db); eq(IC.Curation.Observation("emote:wave").sound, "self"); eq(IC.Curation.Observation("emote:wave").animation, "yes")
    end)
    test("duplicate references validate aliases and never redirect an action's token", function()
        open(); local old = IC.Actions.Resolve("emote:wave").payload
        assert(not IC.Curation.Save("emote:wave", "duplicate", "unknown", "unknown", "/missing"))
        assert(not IC.Curation.Save("emote:wave", "duplicate", "unknown", "unknown", "/wave"))
        assert(IC.Curation.Save("emote:wave", "duplicate", "unknown", "unknown", "/joke"))
        eq(IC.Curation.Record("emote:wave").duplicateOf, "emote:silly")
        eq(IC.Actions.Resolve("emote:wave").payload, old)
    end)
    test("review queues collapse exact token aliases, preserve a stable snapshot and track icon approval", function()
        open(); EMOTE1_TOKEN, EMOTE1_CMD1, EMOTE1_CMD2 = "SILLY", "/silly", "/joke"; IC.Emotes.Validate()
        local queue = IC.Curation.Queue("pending"); eq(#queue, 1); eq(queue[1], "emote:silly")
        IC.Curation.Save("emote:joke", "keep", "unknown", "unknown", "", "verbatim note", true)
        eq(#queue, 1); eq(#IC.Curation.Queue("pending"), 0); eq(#IC.Curation.Queue("icons"), 0)
        assert(contains(IC.Curation.Queue("all"), "emote:silly")); eq(IC.Curation.Record("emote:silly").notes, "verbatim note")
        EMOTE1_TOKEN, EMOTE1_CMD1, EMOTE1_CMD2 = nil, nil, nil; IC.Emotes.Validate()
    end)
    test("v5 migration preserves layouts quotes icons pins and explicit empty choices", function()
        local db = open(); db.version = 5
        local profile = IC.Profile(); profile.pools.quotes.lines = { "don't replace me" }; profile.favorites = {}
        profile.quick, profile.emoteScope, profile.emoteReview = nil, nil, nil; profile.emoteFilter = "sound"
        profile.emoteOverrides["emote:wave"] = { icon = "custom" }; IC.Layout().bars[1].x = 271
        open(db); eq(db.version, 10); eq(IC.Profile().emoteFilter, "all"); eq(IC.Profile().emoteScope, "essentials")
        eq(#IC.Profile().favorites, 0); eq(IC.Profile().pools.quotes.lines[1], "don't replace me"); eq(IC.Layout().bars[1].x, 271)
        eq(IC.Actions.Resolve("emote:wave").icon, "custom")
    end)
    test("text-only is an explicit recorded decision and all commands remain recoverable", function()
        open(); local action = IC.Actions.Resolve("emote:wave")
        IC.Curation.Save(action.id, "text", "unknown", "unknown")
        eq(IC.Curation.Observation(action.id).sound, "silent"); eq(IC.Curation.Observation(action.id).animation, "no")
        assert(not IC.Curation.Included(action)); assert(IC.Actions.Resolve(action.id)); eq(IC.Curation.Record(action.id).choice, "text")
    end)
    test("different catalog commands mapped to the same client token are reviewed only once", function()
        open(); EMOTE1_TOKEN, EMOTE1_CMD1, EMOTE1_CMD2 = "WAVE", "/wave", "/hello"; IC.Emotes.Validate()
        eq(IC.Actions.Resolve("emote:hello").payload, "WAVE"); eq(#IC.Curation.Queue("pending"), 1)
        IC.Curation.Save("emote:wave", "keep", "unknown", "unknown", "", "", true)
        eq(#IC.Curation.Queue("pending"), 0); eq(#IC.Curation.Queue("icons"), 0)
        assert(IC.Emotes.Search(IC.Actions.Resolve("emote:wave"), "hello"))
        EMOTE1_TOKEN, EMOTE1_CMD1, EMOTE1_CMD2 = nil, nil, nil; IC.Emotes.Validate()
    end)
end
